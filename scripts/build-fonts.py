# -*- coding: utf-8 -*-
# Run from the project root: python scripts/build-fonts.py  (needs: pip install fonttools brotli)
"""Builds the site's own font files:
 - the latin file of each cut, copied from @fontsource;
 - one tiny "bs" file per cut holding only Č č Ć ć Đ đ Š š Ž ž, cut from the
   latin-ext file (the whole latin-ext file is ~32 KB per weight, and đ also
   pulled in the vietnamese file);
 - metric-matched fallback faces (Arial for Montserrat, Georgia for Playfair),
   so text keeps its size and line breaks while the real font is on its way.
Writes src/assets/fonts/* and src/fonts.css."""
import io, os, re, shutil
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = os.getcwd()
FS = os.path.join(ROOT, 'node_modules', '@fontsource')
OUT = os.path.join(ROOT, 'src', 'assets', 'fonts')
os.makedirs(OUT, exist_ok=True)

BS = [0x0106, 0x0107, 0x010C, 0x010D, 0x0110, 0x0111, 0x0160, 0x0161, 0x017D, 0x017E]
BS_RANGE = 'U+0106-0107, U+010C-010D, U+0110-0111, U+0160-0161, U+017D-017E'

CUTS = [
    # family, package, file stem, weight, style
    ('Playfair Display', 'playfair-display', 'playfair-display', 400, 'normal'),
    ('Playfair Display', 'playfair-display', 'playfair-display', 400, 'italic'),
    ('Playfair Display', 'playfair-display', 'playfair-display', 500, 'normal'),
    ('Montserrat', 'montserrat', 'montserrat', 300, 'normal'),
    ('Montserrat', 'montserrat', 'montserrat', 400, 'normal'),
    ('Montserrat', 'montserrat', 'montserrat', 500, 'normal'),
    ('Montserrat', 'montserrat', 'montserrat', 600, 'normal'),
    ('Anton', 'anton', 'anton', 400, 'normal'),
]

# the latin unicode-range exactly as fontsource declares it
css400 = io.open(os.path.join(FS, 'montserrat', '400.css'), encoding='utf-8').read()
LATIN_RANGE = re.findall(r'/\* montserrat-latin-400-normal \*/[\s\S]*?unicode-range:\s*([^;]+);', css400)[0].strip()

rules = []
total_before = total_after = 0
for family, pkg, stem, weight, style in CUTS:
    files = os.path.join(FS, pkg, 'files')
    latin = os.path.join(files, f'{stem}-latin-{weight}-{style}.woff2')
    ext = os.path.join(files, f'{stem}-latin-ext-{weight}-{style}.woff2')
    slug = f'{stem}-{weight}{"-italic" if style == "italic" else ""}'
    shutil.copyfile(latin, os.path.join(OUT, f'{slug}-latin.woff2'))
    rules.append(f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-display: swap;
  font-weight: {weight};
  src: url('./assets/fonts/{slug}-latin.woff2') format('woff2');
  unicode-range: {LATIN_RANGE};
}}""")
    if family == 'Anton':
        continue  # the logo's "387 WEDDINGS" needs no other letters
    total_before += os.path.getsize(ext)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = []
    opts.notdef_outline = True
    font = TTFont(ext)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=BS)
    sub.subset(font)
    out = os.path.join(OUT, f'{slug}-bs.woff2')
    font.flavor = 'woff2'
    font.save(out)
    total_after += os.path.getsize(out)
    rules.append(f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-display: swap;
  font-weight: {weight};
  src: url('./assets/fonts/{slug}-bs.woff2') format('woff2');
  unicode-range: {BS_RANGE};
}}""")

# ── metric-matched fallbacks ──────────────────────────────────────────────
SAMPLE = 'Zabilježimo emocije koje traju kada sve drugo prođe. Vaša priča, naša umjetnost. Pratimo parove kroz Bosnu i Balkan već godinama.'

def avg_width(font):
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    upm = font['head'].unitsPerEm
    ws = [hmtx[cmap[ord(c)]][0] for c in SAMPLE if ord(c) in cmap]
    return sum(ws) / len(ws) / upm

def metrics(font):
    upm = font['head'].unitsPerEm
    hhea = font['hhea']
    return hhea.ascent / upm, abs(hhea.descent) / upm, hhea.lineGap / upm

def fallback(name, real_path, local_path, local_name):
    real = TTFont(real_path)
    loc = TTFont(local_path)
    size = avg_width(real) / avg_width(loc)
    a, d, g = metrics(real)
    return f"""@font-face {{
  font-family: '{name}';
  src: local('{local_name}');
  size-adjust: {size * 100:.2f}%;
  ascent-override: {a / size * 100:.2f}%;
  descent-override: {d / size * 100:.2f}%;
  line-gap-override: {g / size * 100:.2f}%;
}}"""

WIN = 'C:/Windows/Fonts'
fb = [
    fallback('Montserrat Fallback', os.path.join(FS, 'montserrat', 'files', 'montserrat-latin-400-normal.woff2'), f'{WIN}/arial.ttf', 'Arial'),
    fallback('Playfair Display Fallback', os.path.join(FS, 'playfair-display', 'files', 'playfair-display-latin-400-normal.woff2'), f'{WIN}/georgia.ttf', 'Georgia'),
]

header = """/* Generated by the font build (scripts/build-fonts.py): each cut's latin
   file, plus a tiny file holding only Č č Ć ć Đ đ Š š Ž ž instead of the whole
   latin-ext set; and fallback faces sized to match, so text does not reflow
   when the real font arrives. Caveat is still loaded from @fontsource (the
   panel offers it; it is fetched only if a text uses it). */
"""
io.open(os.path.join(ROOT, 'src', 'fonts.css'), 'w', encoding='utf-8', newline='\n').write(
    header + '\n' + '\n\n'.join(fb + rules) + '\n')
print(f'latin-ext prije: {total_before // 1024} KB za 7 rezova; bs datoteke sada: {total_after // 1024} KB')
print('\n'.join(fb))
